// Bundles pg and mysql2 into vendor/ with esbuild and writes license notices. Run via `npm run build`.
// Fails when a plugin file is over 1 MiB or a frame bundle contains eval or new Function.
import { copyFile, mkdir, readdir, readFile, rm, stat, writeFile } from 'node:fs/promises'
import { join, relative } from 'node:path'
import { build } from 'esbuild'

const ROOT = join(import.meta.dirname, '..')
const VENDOR = join(ROOT, 'vendor')
const ENTRIES = join(ROOT, 'build', 'entries')
const MAX_FILE_BYTES = 1024 * 1024
const SKIP_DIRS = new Set(['node_modules', '.git', '.orca', 'dist', 'coverage'])

// A worker bundle runs in Node; a frame bundle runs in an isolated frame under a strict CSP.
const BUNDLES = [
  { name: 'pg', kind: 'worker' },
  { name: 'mysql2', kind: 'worker' },
  { name: 'codemirror', kind: 'frame' },
]

// CommonJS dependencies call require() on Node built-ins, which ESM output lacks.
const REQUIRE_BANNER =
  "import { createRequire as __createRequire } from 'node:module';const require = __createRequire(import.meta.url);"

const DYNAMIC_CODE = [
  { label: 'eval', pattern: /(?<![\w$.])eval\s*\(/ },
  { label: 'new Function', pattern: /new\s+Function\b/ },
]

function fail(message) {
  process.stderr.write(`build failed: ${message}\n`)
  process.exit(1)
}

async function bundle({ name, kind }) {
  const worker = kind === 'worker'
  const result = await build({
    entryPoints: [join(ENTRIES, `${name}.ts`)],
    outfile: join(VENDOR, `${name}.js`),
    bundle: true,
    format: 'esm',
    platform: worker ? 'node' : 'browser',
    target: worker ? 'node24' : 'es2022',
    minify: true,
    // Keep non-ASCII text as written. By default esbuild escapes it, which turns iconv-lite's
    // codepage tables (bundled by mysql2) into long `\xNN` runs that read as obfuscated code to
    // reviewers and to the Orca plugin directory's scanner. Node reads ESM source as UTF-8.
    charset: worker ? 'utf8' : 'ascii',
    legalComments: 'none',
    metafile: true,
    logLevel: 'warning',
    // pg loads the optional native binding in a try/catch; the plugin never ships it.
    external: worker ? ['pg-native', 'cloudflare:sockets'] : [],
    banner: worker ? { js: REQUIRE_BANNER } : {},
  })
  return result.metafile
}

// Package roots (node_modules/<name> or node_modules/@scope/<name>) of everything bundled.
function bundledPackages(metafile) {
  const packages = new Set()
  for (const input of Object.keys(metafile.inputs)) {
    const parts = input.split('/')
    const at = parts.lastIndexOf('node_modules')
    if (at === -1) continue
    const scoped = parts[at + 1]?.startsWith('@')
    packages.add(parts.slice(0, at + (scoped ? 3 : 2)).join('/'))
  }
  return [...packages].sort()
}

async function licenseText(dir) {
  for (const entry of await readdir(dir)) {
    if (/^(licen[sc]e|copying)(\.|$)/i.test(entry))
      return (await readFile(join(dir, entry), 'utf8')).trim()
  }
  return null
}

async function notice(packageDir) {
  const dir = join(ROOT, packageDir)
  const pkg = JSON.parse(await readFile(join(dir, 'package.json'), 'utf8'))
  const license = typeof pkg.license === 'string' ? pkg.license : (pkg.license?.type ?? 'UNKNOWN')
  const text = await licenseText(dir)
  const header = `## ${pkg.name}@${pkg.version}\n\nLicense: ${license}\n`
  return `${header}\n${text ? `\`\`\`text\n${text}\n\`\`\`` : '(no license file shipped in the package)'}\n`
}

async function writeNotices(packageDirs) {
  const sections = await Promise.all(packageDirs.map(notice))
  const intro =
    '# Third-party notices\n\nGenerated by `npm run build`. Do not edit.\n\nThe bundles in this directory include the following packages.\n'
  await writeFile(join(VENDOR, 'THIRD-PARTY-NOTICES.md'), `${intro}\n${sections.join('\n')}`)
}

function checkDynamicCode(name, code) {
  for (const { label, pattern } of DYNAMIC_CODE) {
    if (pattern.test(code)) {
      fail(`frame bundle vendor/${name}.js contains \`${label}\`, which the frame CSP forbids`)
    }
  }
}

async function listFiles(dir) {
  const files = []
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (SKIP_DIRS.has(entry.name)) continue
    const path = join(dir, entry.name)
    if (entry.isDirectory()) files.push(...(await listFiles(path)))
    else files.push(path)
  }
  return files
}

async function checkFileSizes() {
  const sizes = []
  for (const file of await listFiles(ROOT)) {
    const { size } = await stat(file)
    if (size > MAX_FILE_BYTES) {
      fail(
        `${relative(ROOT, file)} is ${size} bytes; the Orca directory allows ${MAX_FILE_BYTES} (1 MiB) per file`,
      )
    }
    if (file.startsWith(`${VENDOR}/`)) sizes.push({ file: relative(ROOT, file), size })
  }
  return sizes
}

async function main() {
  await rm(VENDOR, { recursive: true, force: true })
  await mkdir(VENDOR, { recursive: true })

  const packages = new Set()
  for (const entry of BUNDLES) {
    for (const dir of bundledPackages(await bundle(entry))) packages.add(dir)
  }
  await writeNotices([...packages].sort())
  // The editor entry only re-exports, so it doubles as the declarations a frame imports against.
  await copyFile(join(ENTRIES, 'codemirror.ts'), join(VENDOR, 'codemirror.d.ts'))

  for (const { name, kind } of BUNDLES) {
    if (kind === 'frame') checkDynamicCode(name, await readFile(join(VENDOR, `${name}.js`), 'utf8'))
  }

  for (const { file, size } of await checkFileSizes()) {
    process.stdout.write(`${file.padEnd(40)} ${String(size).padStart(8)} bytes\n`)
  }
}

await main()
